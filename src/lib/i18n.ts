let currentLocale: Locale = 'en';

export function setLocale(locale: Locale) {
  currentLocale = locale;
  if (typeof window !== 'undefined') {
    localStorage.setItem('bizzbills:locale', locale);
  }
}

export function getLocale(): Locale {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('bizzbills:locale') as Locale;
    if (saved && translations[saved]) return saved;
  }
  return currentLocale;
}

export function t(key: string, locale?: Locale): string {
  const loc = locale || getLocale();
  return translations[loc]?.[key] || translations.en[key] || key;
}

export function getLocaleName(locale: Locale): string {
  return locale === 'hi' ? 'हिन्दी' : 'English';
}

export function getAvailableLocales(): Array<{ code: Locale; name: string }> {
  return [
    { code: 'en', name: 'English' },
    { code: 'hi', name: 'हिन्दी' },
  ];
}
